/**
 * The evidence registry.
 *
 * Every factual claim on the result page — body-composition formulas, safety
 * screening, exercise selection, weekly movement guidelines, equipment advice,
 * anatomy/mesh licensing, percentile datasets — resolves to one or more
 * entries here. This file is the single source of truth the "Sources &
 * methods" surface reads from, and every other data file (exercises, kit,
 * goals, screening) references it by id rather than re-typing a citation.
 *
 * Kinds are kept deliberately separate and are never collapsed into each
 * other in copy:
 *   - guideline           an official public-health or professional body position
 *   - rct                 a randomised controlled trial
 *   - meta_analysis       a systematic review / meta-analysis / network meta-analysis
 *   - observational       cohort/case-control association — correlation, not proof of causation
 *   - biomechanical        EMG, cadaver, or joint-mechanics inference — plausible, not outcome evidence
 *   - sport_extrapolation  evidence from athletes/a sport applied to general users
 *   - editorial_inference  a product/engineering judgement with no direct trial behind it
 *   - dataset             a reference/percentile dataset (e.g. NHANES)
 *   - asset_license        provenance/licence for a visual asset (mesh, anatomy model)
 *
 * "Never turn association into causation": every `observational` source's
 * `claimSupported` copy is written as a correlation, and nothing derived from
 * it is allowed to say "prevents" or "causes" — enforced by the copy in
 * data/exercises.ts and checked by tests/integrity.test.ts.
 */

export type EvidenceKind =
  | "guideline"
  | "rct"
  | "meta_analysis"
  | "observational"
  | "biomechanical"
  | "sport_extrapolation"
  | "editorial_inference"
  | "dataset"
  | "asset_license"

